# FOR LOOPS
# USED FOR SEQUENTIAL TRAVERSAL. FOR TRAVERSING LIST, STRING AND TUPLES etc.

nums = [1,2,3,4,5]
for val in nums:
    print(val)

fruits = ["APPLE","ORANGE","MANGO","BANANA"]
for val in fruits:
    print(val)

tup = (1,2,3,4,2,8,9)
for val in tup:
    print(val)

veg = ("POTATO","TOMATO","ONION","CARROT")
for val in veg:
    print(val)

name = "DANIYAL ARAIN"
for char in name:
    print(char)
