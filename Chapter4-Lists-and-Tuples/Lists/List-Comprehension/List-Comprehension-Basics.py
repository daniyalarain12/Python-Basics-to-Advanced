# LIST COMPREHENSION
# List comprehension in Python is a short and simple way to create a new list from an existing iterable using a single line of code.

# SYNTAX
# new_list = [expression for item in iterable if condition]
# new_list = [value_if_true if condition else value_if_false for item in iterable]

# expression -> Value or operation to add in the new list
# item -> Variable used to access each element
# iterable -> Collection like list, tuple, set, etc.
# condition -> Optional filter to check whether item should be added
